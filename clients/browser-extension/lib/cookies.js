/**
 * Cookie helpers for the Media Vault Companion extension.
 *
 * Zero-build ES module. Browser APIs are only touched inside functions so the
 * module can be imported in Node for unit tests.
 */

export const YOUTUBE_COOKIE_ORIGINS = [
  "https://*.youtube.com/*",
  "https://youtube.com/*",
  "https://*.google.com/*",
  "https://*.googlevideo.com/*",
  "https://youtu.be/*",
];

export const ALLOWED_COOKIE_DOMAINS = [
  "youtube.com",
  "google.com",
  "googlevideo.com",
  "youtu.be",
];

function getExtApi() {
  const api = globalThis.browser || globalThis.chrome;
  return api && typeof api === "object" ? api : null;
}

export function isAllowedCookieDomain(rawDomain) {
  if (typeof rawDomain !== "string" || !rawDomain) return false;

  // Reject any whitespace or control characters BEFORE trimming so inputs like
  // "youtube.com\r\n" or "youtube.com\t" never bypass domain validation.
  if (/\s/.test(rawDomain)) return false;
  for (let i = 0; i < rawDomain.length; i++) {
    const code = rawDomain.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) return false;
  }

  let d = rawDomain.toLowerCase();
  while (d.startsWith(".")) d = d.slice(1);

  if (!d) return false;
  if (d.includes("/") || d.includes(":")) return false;

  for (const allowed of ALLOWED_COOKIE_DOMAINS) {
    const a = String(allowed).toLowerCase().trim();
    if (!a) continue;
    if (d === a) return true;
    if (d.endsWith("." + a)) return true;
  }
  return false;
}

const CONTROL_CHARS_RE = /[\r\n\t\0]/g;

function stripControl(value) {
  return String(value == null ? "" : value).replace(CONTROL_CHARS_RE, "");
}

function hasWhitespaceOrControl(value) {
  const s = String(value == null ? "" : value);
  if (/\s/.test(s)) return true;
  for (let i = 0; i < s.length; i++) {
    const code = s.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) return true;
  }
  return false;
}

export function formatNetscapeCookies(cookies) {
  const input = Array.isArray(cookies) ? cookies : [];
  const seen = new Set();
  const lines = [];
  const domainSet = new Set();

  for (const c of input) {
    if (!c || typeof c !== "object" || Array.isArray(c)) continue;

    const rawDomain = c.domain != null ? c.domain : c.host;
    if (!isAllowedCookieDomain(rawDomain)) continue;

    const rawName = c.name;
    if (typeof rawName !== "string" || rawName === "") continue;
    if (c.value === undefined) continue;

    const rawPath = c.path == null ? "/" : String(c.path);
    if (hasWhitespaceOrControl(rawName) || hasWhitespaceOrControl(rawPath)) continue;

    let domain = stripControl(rawDomain);
    let path = stripControl(rawPath);
    const name = stripControl(rawName);
    const value = stripControl(c.value);

    if (!domain || !name) continue;
    if (hasWhitespaceOrControl(domain) || hasWhitespaceOrControl(name)) continue;

    // Normalize domain + includeSubdomains.
    let includeSubdomains;
    let normalizedDomain = domain;
    if (c.hostOnly === true) {
      while (normalizedDomain.startsWith(".")) normalizedDomain = normalizedDomain.slice(1);
      includeSubdomains = "FALSE";
    } else {
      if (!normalizedDomain.startsWith(".")) normalizedDomain = "." + normalizedDomain;
      includeSubdomains = "TRUE";
    }

    if (!path || typeof path !== "string") path = "/";
    if (!path.startsWith("/")) path = "/" + path;

    const secure = c.secure ? "TRUE" : "FALSE";

    let expiry = "0";
    const expNum = Number(c.expirationDate);
    if (!(c.session === true) && Number.isFinite(expNum) && expNum > 0) {
      expiry = String(Math.floor(expNum));
    }

    const key = `${normalizedDomain}\t${path}\t${name}`;
    if (seen.has(key)) continue;
    seen.add(key);

    const domainField = c.httpOnly === true ? `#HttpOnly_${normalizedDomain}` : normalizedDomain;

    lines.push(
      `${domainField}\t${includeSubdomains}\t${path}\t${secure}\t${expiry}\t${name}\t${value}`,
    );

    domainSet.add(normalizedDomain.replace(/^#HttpOnly_/, "").replace(/^\./, ""));
  }

  // Deterministic sort by domain, path, name.
  const parsedLines = lines.map((line) => {
    const parts = line.split("\t");
    return { line, domain: parts[0], path: parts[2], name: parts[5] };
  });
  parsedLines.sort((a, b) => {
    if (a.domain < b.domain) return -1;
    if (a.domain > b.domain) return 1;
    if (a.path < b.path) return -1;
    if (a.path > b.path) return 1;
    if (a.name < b.name) return -1;
    if (a.name > b.name) return 1;
    return 0;
  });
  const sortedLines = parsedLines.map((p) => p.line);

  const domains = [...domainSet].sort();

  const header =
    "# Netscape HTTP Cookie File\n# Generated by Media Vault Companion (YouTube/Google scoped)\n\n";
  const text =
    header + sortedLines.join("\n") + (sortedLines.length ? "\n" : "");

  return { text, count: sortedLines.length, domains };
}

async function permissionCall(method, details) {
  const api = getExtApi();
  const perms = api?.permissions;
  if (!perms || typeof perms[method] !== "function") return false;
  const fn = perms[method];

  try {
    const maybe = fn.call(perms, details);
    if (maybe && typeof maybe.then === "function") {
      const result = await maybe;
      return result;
    }
    if (typeof maybe === "boolean") return maybe;
    if (maybe !== undefined && maybe !== null) return maybe;
  } catch (_) {
    // Fall through to callback style.
  }

  return await new Promise((resolve) => {
    try {
      fn.call(perms, details, (result) => {
        const lastError = api?.runtime?.lastError;
        if (lastError) resolve(false);
        else resolve(result);
      });
    } catch (_) {
      resolve(false);
    }
  });
}

export async function hasCookiePermission() {
  return permissionCall("contains", {
    permissions: ["cookies"],
    origins: YOUTUBE_COOKIE_ORIGINS,
  });
}

export async function requestCookiePermission() {
  return permissionCall("request", {
    permissions: ["cookies"],
    origins: YOUTUBE_COOKIE_ORIGINS,
  });
}

export async function revokeCookiePermission() {
  return permissionCall("remove", {
    permissions: ["cookies"],
    origins: YOUTUBE_COOKIE_ORIGINS,
  });
}

export async function collectYouTubeCookies() {
  const api = getExtApi();
  if (!api?.cookies || typeof api.cookies.getAll !== "function") {
    throw new Error("Cookies API is not available in this browser.");
  }

  const all = [];
  for (const domain of ALLOWED_COOKIE_DOMAINS) {
    const list = await new Promise((resolve) => {
      const cookiesApi = api.cookies;
      try {
        const maybe = cookiesApi.getAll({ domain });
        if (maybe && typeof maybe.then === "function") {
          maybe
            .then((result) => resolve(Array.isArray(result) ? result : []))
            .catch(() => resolve([]));
          return;
        }
        if (Array.isArray(maybe)) {
          resolve(maybe);
          return;
        }
      } catch (_) {
        // Fall through.
      }
      try {
        cookiesApi.getAll({ domain }, (result) => {
          const lastError = api?.runtime?.lastError;
          if (lastError) resolve([]);
          else resolve(Array.isArray(result) ? result : []);
        });
      } catch (_) {
        resolve([]);
      }
    });
    if (Array.isArray(list)) all.push(...list);
  }
  return all;
}